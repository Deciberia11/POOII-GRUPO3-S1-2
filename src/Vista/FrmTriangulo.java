    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    if (superficie.getFigurasGeometricas().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No hay figuras agregadas."
        );

        return;
    }

    String resultado = "";

    for (Figura_Geometrica figura
            : superficie.getFigurasGeometricas()) {

        resultado += figura.getNombre()
                + " - Área: "
                + figura.calcularArea()
                + "\n";
    }

    javax.swing.JOptionPane.showMessageDialog(
            this,
            resultado
    );        // TODO add your handling code here:
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    try{
        String nombre = txtNombre.getText();
        
        int x1 = Integer.parseInt(txtX1.getText());
        int y1 = Integer.parseInt(txtY1.getText());
        
        int x2 = Integer.parseInt(txtX2.getText());
        int y2 = Integer.parseInt(txtY2.getText());
        
        int x3 = Integer.parseInt(txtX3.getText());
        int y3 = Integer.parseInt(txtY3.getText());
        
        Punto punto1 = new Punto (x1, y1);
        Punto punto2 = new Punto (x2, y2);
        Punto punto3 = new Punto (x3, y3);
        
        Triangulo triangulo = new Triangulo(
                nombre,
                punto1,
                punto2,
                punto3
        );
        
        txtArea.setText(
            String.valueOf(triangulo.calcularArea())
        );
        
        txtRegular.setText(
                String.valueOf(triangulo.esRegular())
        );
    } catch(NumberFormatException e){
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese valores  numericos en las coordenadas.");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

