    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       if (txtNombre.getText().trim().isEmpty()
            || txtX1.getText().trim().isEmpty()
            || txtY1.getText().trim().isEmpty()
            || txtX2.getText().trim().isEmpty()
            || txtY2.getText().trim().isEmpty()
            || txtX3.getText().trim().isEmpty()
            || txtY3.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Complete todos los campos."
        );

        return;
    }

    try {

        String nombre = txtNombre.getText();

        int x1 = Integer.parseInt(txtX1.getText());
        int y1 = Integer.parseInt(txtY1.getText());

        int x2 = Integer.parseInt(txtX2.getText());
        int y2 = Integer.parseInt(txtY2.getText());

        int x3 = Integer.parseInt(txtX3.getText());
        int y3 = Integer.parseInt(txtY3.getText());

        Punto punto1 = new Punto(x1, y1);
        Punto punto2 = new Punto(x2, y2);
        Punto punto3 = new Punto(x3, y3);

        Triangulo triangulo = new Triangulo(
                nombre,
                punto1,
                punto2,
                punto3
        );

        superficie.agregarFigura(triangulo);

        txtArea.setText(
                String.valueOf(triangulo.calcularArea())
        );

        txtRegular.setText(
                String.valueOf(triangulo.esRegular())
        );

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Figura agregada correctamente."
        );

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Las coordenadas deben ser números enteros."
        );
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

